"""Writes src/FellowshipSim.UI/Build/GameIcons.cs from a Codex datamine export (entities.jsonl).

The UI shows each talent, trait, blessing, legendary, weapon ability, gem and hero with its game icon from the Codex CDN.
Run it again after a new datamine:

    python -I tools/generate_game_icons.py [path/to/entities.jsonl]

The default path is the Codex cache, ~/.fellowsim/cache/codex/entities.jsonl.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "FellowshipSim.UI", "Build", "GameIcons.cs")


def cs(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.expanduser("~"), ".fellowsim", "cache", "codex", "entities.jsonl")
    rows = [json.loads(line) for line in open(path, encoding="utf-8") if line.strip()]

    def of(kind):
        return sorted((r for r in rows if r.get("$type") == kind and r.get("icon")), key=lambda r: int(r["id"]))

    def by_id(name, kind, where=lambda r: True):
        entries = [f"        [{int(r['id'])}] = {cs(r['icon'])}," for r in of(kind) if where(r)]
        return [f"    /// <summary>Icons of the datamine's {kind} records, by ID.</summary>",
                f"    public static IReadOnlyDictionary<int, string> {name} {{ get; }} = new Dictionary<int, string>",
                "    {", *entries, "    };", ""]

    def max_ranks(name, kind):
        entries = [f"        [{int(r['id'])}] = {int(r['maxRank'])}," for r in rows if r.get("$type") == kind and r.get("maxRank")]
        return [f"    /// <summary>The highest rank of each {kind}, by ID.</summary>",
                f"    public static IReadOnlyDictionary<int, int> {name} {{ get; }} = new Dictionary<int, int>",
                "    {", *entries, "    };", ""]

    # The first gem item of each colour ("Small Amethyst"); the gem-type records all have the same icon.
    colours = {}
    for r in of("gem"):
        colours.setdefault(r["name"].split()[-1], r["icon"])
    gems = [f"        [{cs(name)}] = {cs(icon)}," for name, icon in sorted(colours.items())]
    heroes = [f"        [{cs(r['name'])}] = {cs(r['portrait'])},"
              for r in sorted((r for r in rows if r.get("$type") == "hero" and r.get("portrait")), key=lambda r: r["name"])]

    lines = [
        "// <auto-generated> by tools/generate_game_icons.py from the Codex datamine export. Run the script again after a new",
        "// datamine instead of editing this file. </auto-generated>",
        "namespace FellowshipSim.UI.Build;",
        "",
        "/// <summary>",
        "/// Game icons from the datamine, for display alone: the engine never reads them. <see cref=\"Url\"/> is an icon's image",
        "/// on the Codex CDN.",
        "/// </summary>",
        "public static class GameIcons",
        "{",
        "    /// <summary>The image of icon <paramref name=\"icon\"/> on the Codex CDN.</summary>",
        "    public static string Url(string icon) => $\"https://cdn.codex.fellowshipanalyzer.com/ui/{icon}_full.webp\";",
        "",
        *by_id("Talents", "talent"),
        *by_id("Traits", "trait"),
        *by_id("Blessings", "blessing"),
        *by_id("LegendaryPowers", "legendary-power"),
        *by_id("WeaponAbilities", "ability", lambda r: r.get("category") == "Weapon"),
        *max_ranks("TraitMaxRanks", "trait"),
        *max_ranks("BlessingMaxRanks", "blessing"),
        "    /// <summary>Icons of the gem colours, by name (\"Sapphire\").</summary>",
        "    public static IReadOnlyDictionary<string, string> Gems { get; } = new Dictionary<string, string>",
        "    {", *gems, "    };",
        "",
        "    /// <summary>Hero portraits, by hero name.</summary>",
        "    public static IReadOnlyDictionary<string, string> Heroes { get; } = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)",
        "    {", *heroes, "    };",
        "}",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
